create or replace view public.sipic_latest_observations
with (security_invoker = true)
as
select distinct on (o.station_id)
  o.*,
  s.code as station_code,
  s.name as station_name,
  s.sector_id
from public.sipic_observations o
join public.sipic_stations s on s.id = o.station_id
order by o.station_id, o.observed_at desc;

grant select on public.sipic_latest_observations to anon, authenticated;

create or replace view public.sipic_active_alerts
with (security_invoker = true)
as
select
  a.*,
  s.code as sector_code,
  s.name as sector_name
from public.sipic_alerts a
left join public.sipic_sectors s on s.id = a.sector_id
where a.active = true
  and (a.valid_until is null or a.valid_until >= now());

grant select on public.sipic_active_alerts to anon, authenticated;

