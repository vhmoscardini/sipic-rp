-- SIPIC-RP — núcleo de dados isolado por prefixo sipic_
-- Projetado para coexistir com outros sistemas no mesmo projeto Supabase.

create extension if not exists pgcrypto;

create or replace function public.sipic_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.sipic_sectors (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  zone text not null,
  latitude double precision not null,
  longitude double precision not null,
  imperviousness numeric(5,4) not null default 0.5 check (imperviousness between 0 and 1),
  ndvi numeric(5,4) not null default 0.3 check (ndvi between -1 and 1),
  sky_view_factor numeric(5,4) not null default 0.6 check (sky_view_factor between 0 and 1),
  building_density numeric(5,4) not null default 0.5 check (building_density between 0 and 1),
  ventilation_factor numeric(5,4) not null default 0.5 check (ventilation_factor between 0 and 1),
  heat_offset_c numeric(6,3) not null default 0,
  is_reference boolean not null default false,
  geometry_geojson jsonb,
  metadata jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sipic_stations (
  id uuid primary key default gen_random_uuid(),
  sector_id uuid references public.sipic_sectors(id) on delete set null,
  code text not null unique,
  name text not null,
  source text not null,
  station_type text not null default 'virtual_grid',
  latitude double precision not null,
  longitude double precision not null,
  status text not null default 'online' check (status in ('online','warning','offline','maintenance')),
  last_seen_at timestamptz,
  quality_score numeric(5,2) not null default 100 check (quality_score between 0 and 100),
  metadata jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sipic_observations (
  id bigint generated by default as identity primary key,
  station_id uuid not null references public.sipic_stations(id) on delete cascade,
  observed_at timestamptz not null,
  ingested_at timestamptz not null default now(),
  source text not null,
  data_class text not null default 'observed' check (data_class in ('observed','calculated','modeled','simulated')),
  air_temperature_c numeric(7,3),
  apparent_temperature_c numeric(7,3),
  surface_temperature_c numeric(7,3),
  relative_humidity_pct numeric(7,3),
  surface_pressure_hpa numeric(9,3),
  wind_speed_ms numeric(7,3),
  wind_direction_deg numeric(7,3),
  shortwave_radiation_wm2 numeric(10,3),
  precipitation_mm numeric(9,3),
  weather_code integer,
  pm25_ugm3 numeric(9,3),
  pm10_ugm3 numeric(9,3),
  us_aqi numeric(8,3),
  ozone_ugm3 numeric(10,3),
  nitrogen_dioxide_ugm3 numeric(10,3),
  sulphur_dioxide_ugm3 numeric(10,3),
  carbon_monoxide_ugm3 numeric(12,3),
  uv_index numeric(7,3),
  ndvi numeric(6,4),
  urban_heat_island_c numeric(7,3),
  risk_score numeric(6,2),
  quality_score numeric(5,2) not null default 90 check (quality_score between 0 and 100),
  raw_payload jsonb not null default '{}'::jsonb,
  unique (station_id, observed_at, source)
);

create table if not exists public.sipic_predictions (
  id bigint generated by default as identity primary key,
  sector_id uuid not null references public.sipic_sectors(id) on delete cascade,
  generated_at timestamptz not null,
  valid_at timestamptz not null,
  horizon_hours integer not null check (horizon_hours >= 0),
  model_version text not null,
  source text not null default 'hybrid_open_meteo_morphology',
  air_temperature_c numeric(7,3),
  surface_temperature_c numeric(7,3),
  apparent_temperature_c numeric(7,3),
  urban_heat_island_c numeric(7,3),
  lower_bound_c numeric(7,3),
  upper_bound_c numeric(7,3),
  risk_score numeric(6,2),
  risk_level text check (risk_level in ('low','moderate','high','critical')),
  confidence_pct numeric(5,2) check (confidence_pct between 0 and 100),
  explanations jsonb not null default '[]'::jsonb,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (sector_id, generated_at, valid_at, model_version)
);

create table if not exists public.sipic_alerts (
  id uuid primary key default gen_random_uuid(),
  sector_id uuid references public.sipic_sectors(id) on delete cascade,
  fingerprint text not null unique,
  generated_at timestamptz not null default now(),
  valid_from timestamptz not null,
  valid_until timestamptz,
  alert_type text not null default 'thermal_risk',
  level text not null check (level in ('info','attention','warning','critical')),
  title text not null,
  message text not null,
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  acknowledged_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sipic_ingestion_runs (
  id uuid primary key default gen_random_uuid(),
  source text not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  status text not null default 'running' check (status in ('running','success','partial','failed')),
  records_read integer not null default 0,
  records_written integer not null default 0,
  cache_hit boolean not null default false,
  error_message text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.sipic_api_cache (
  cache_key text primary key,
  source text not null,
  payload jsonb not null,
  fetched_at timestamptz not null default now(),
  expires_at timestamptz not null,
  status text not null default 'fresh' check (status in ('fresh','stale','error')),
  error_message text,
  updated_at timestamptz not null default now()
);

create table if not exists public.sipic_reports (
  id uuid primary key default gen_random_uuid(),
  report_type text not null default 'operational_snapshot',
  generated_at timestamptz not null default now(),
  period_start timestamptz,
  period_end timestamptz,
  status text not null default 'ready' check (status in ('queued','processing','ready','failed')),
  payload jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.sipic_settings (
  key text primary key,
  value jsonb not null,
  description text,
  public boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
